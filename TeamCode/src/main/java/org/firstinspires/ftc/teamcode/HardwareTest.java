package org.firstinspires.ftc.teamcode;

import com.qualcomm.robotcore.eventloop.opmode.OpMode;
import com.qualcomm.robotcore.eventloop.opmode.TeleOp;
import com.qualcomm.robotcore.hardware.CRServo;
import com.qualcomm.robotcore.hardware.DcMotor;
import com.qualcomm.robotcore.hardware.DcMotorEx;
import com.qualcomm.robotcore.hardware.DcMotorSimple;

/*
 * HARDWARE TEST - checks every motor and servo one at a time. LIFT THE ROBOT (wheels off the ground) first.
 *
 *   D-pad UP / DOWN   select the device (left_drive, right_drive, intake, launcher, windmill)
 *   Right trigger     run the selected device FORWARD (power = trigger value, 0..1)
 *   Left trigger      run the selected device in REVERSE
 *   A                 reset the encoder counts
 *   X                 windmill DEMO: spins forward 2 s, reverse 2 s, forward 2 s, then stops (works from any selection)
 *
 * Power only goes to the selected device, and only while a trigger is held. Release = stop.
 * Missing devices are reported on screen instead of crashing the OpMode.
 *
 * What to check:
 *   - Right trigger turns the drive wheels so the robot would go FORWARD (goBILDA: left FORWARD, right REVERSE).
 *   - The encoder count / velocity goes UP while running forward. 0 = encoder cable; goes DOWN = direction wrong.
 *   - Launcher velocity climbs while the trigger is held; windmill spins smoothly.
 */
@TeleOp(name = "HardwareTest", group = "Test")
public class HardwareTest extends OpMode {

    // Names must match the Control Hub configuration exactly.
    final String[] NAMES = {"left_drive", "right_drive", "intake", "launcher", "windmill"};
    final double MAX_POWER = 0.5;   // safety cap for a bench test

    // Intake motor direction. If the intake spins the wrong way, flip this one line.
    final DcMotorSimple.Direction INTAKE_DIRECTION = DcMotorSimple.Direction.REVERSE;

    // Launcher (shooter) motor direction. If it spins the wrong way, flip this one line.
    final DcMotorSimple.Direction LAUNCHER_DIRECTION = DcMotorSimple.Direction.REVERSE;

    final DcMotor[] motors = new DcMotor[4];   // indexes 0-3 (drive, drive, intake, launcher)
    CRServo windmill; // initialize windmill using CRServo IG
    String[] status = new String[NAMES.length];

    int selected = 0; // wha?
    final com.qualcomm.robotcore.util.ElapsedTime demoTimer = new com.qualcomm.robotcore.util.ElapsedTime();
    boolean demoRunning = false, prevX;
    double windmillPower = 0;
    boolean prevUp, prevDown;

    @Override
    public void init() {
        for (int i = 0; i < 4; i++) {
            try {
                motors[i] = hardwareMap.get(i == 3 ? DcMotorEx.class : DcMotor.class, NAMES[i]);
                motors[i].setZeroPowerBehavior(DcMotor.ZeroPowerBehavior.BRAKE);
                motors[i].setMode(DcMotor.RunMode.STOP_AND_RESET_ENCODER);
                motors[i].setMode(DcMotor.RunMode.RUN_WITHOUT_ENCODER);
                status[i] = "OK";
            } catch (Exception e) {
                motors[i] = null;
                status[i] = "NOT FOUND in config, please set the [CONFIG] variables to match motors.";
            }
        }
        // Same directions as the competition code.
        if (motors[2] != null) motors[2].setDirection(INTAKE_DIRECTION);
        if (motors[3] != null) motors[3].setDirection(LAUNCHER_DIRECTION);
        if (motors[0] != null) motors[0].setDirection(DcMotor.Direction.FORWARD);
        if (motors[1] != null) motors[1].setDirection(DcMotor.Direction.REVERSE);

        try {
            windmill = hardwareMap.get(CRServo.class, NAMES[4]);
            windmill.setDirection(DcMotorSimple.Direction.REVERSE);
            status[4] = "OK";
        } catch (Exception e) {
            windmill = null;
            status[4] = "NOT FOUND in config";
        }
        telemetry.addLine("HardwareTest ready. D-pad = select, triggers = run, A = reset encoders."); // logs
        telemetry.addLine("If you are facing errors running tests, this usually means you must upgrade your dependencies, for more info please reveiw shooter accuracy in the shooter accuracy test java file compiled on the autonomous shooteraccuracytest.java file ");
    }

    @Override
    public void init_loop() {
        showDevices();
        telemetry.update();
    }

    @Override
    public void loop() {
        // Select device (edge-detected so one press = one step). IDK what that means
        if (gamepad1.dpad_up && !prevUp) selected = (selected + NAMES.length - 1) % NAMES.length;
        if (gamepad1.dpad_down && !prevDown) selected = (selected + 1) % NAMES.length;
        prevUp = gamepad1.dpad_up;
        prevDown = gamepad1.dpad_down;

        if (gamepad1.a) {
            for (DcMotor m : motors) {
                if (m == null) continue;
                m.setMode(DcMotor.RunMode.STOP_AND_RESET_ENCODER);
                m.setMode(DcMotor.RunMode.RUN_WITHOUT_ENCODER);
            }
        }

        double power = (gamepad1.right_trigger - gamepad1.left_trigger) * MAX_POWER;

        // Everything off except the selected device.
        for (int i = 0; i < 4; i++) {
            if (motors[i] != null) motors[i].setPower(i == selected ? power : 0);
        }
        windmillPower = selected == 4 ? power / MAX_POWER : 0;

        // Windmill demo: press X to run it by itself (forward, reverse, forward), no triggers needed.
        if (gamepad1.x && !prevX) {
            demoRunning = true;
            demoTimer.reset();
        }
        prevX = gamepad1.x;
        if (demoRunning) {
            double t = demoTimer.seconds();
            if (t < 2) windmillPower = 1.0;
            else if (t < 4) windmillPower = -1.0;
            else if (t < 6) windmillPower = 1.0;
            else demoRunning = false;
            if (demoRunning) {
                for (int i = 0; i < 4; i++) if (motors[i] != null) motors[i].setPower(0);
            }
        }
        if (windmill != null) windmill.setPower(demoRunning || selected == 4 ? windmillPower : 0);
        telemetry.addData("Windmill power", "%.2f%s", windmillPower, demoRunning ? "  (DEMO)" : "");

        showDevices();
        telemetry.addData("Power", "%.2f", power);
        telemetry.update();
    }

    @Override
    public void stop() {
        for (DcMotor m : motors) if (m != null) m.setPower(0);
        if (windmill != null) windmill.setPower(0);
    }

    private void showDevices() {
        for (int i = 0; i < NAMES.length; i++) {
            String line = (i == selected ? ">> " : "   ") + NAMES[i] + ": " + status[i];
            if (i < 4 && motors[i] != null) {
                line += String.format("  pos=%d", motors[i].getCurrentPosition());
                if (i == 3) line += String.format("  vel=%.0f", ((DcMotorEx) motors[i]).getVelocity());
            }
            telemetry.addLine(line);
        }
    }
}













































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































